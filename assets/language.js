const languageButtons = document.querySelectorAll("[data-language]");
const translatableElements = document.querySelectorAll("[data-i18n]");
const description = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const copy = translations[language];

  if (!copy) {
    return;
  }

  const hashAnchor = window.location.hash
    ? document.querySelector(window.location.hash)
    : null;
  const visibleSection = hashAnchor?.nextElementSibling || (window.scrollY > 0
    ? Array.from(document.querySelectorAll("main section")).find((section) => {
        return section.getBoundingClientRect().bottom > document.querySelector(".masthead").offsetHeight;
      })
    : null);
  const sectionTop = visibleSection?.getBoundingClientRect().top;

  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.title = copy.pageTitle;
  description.setAttribute("content", copy.pageDescription);

  translatableElements.forEach((element) => {
    const translation = copy[element.dataset.i18n];

    if (translation !== undefined) {
      element.innerHTML = translation;
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (visibleSection && sectionTop !== undefined) {
    window.requestAnimationFrame(() => {
      const scrollBehavior = document.documentElement.style.scrollBehavior;
      document.documentElement.style.scrollBehavior = "auto";

      if (hashAnchor) {
        hashAnchor.scrollIntoView();
      } else {
        window.scrollBy(0, visibleSection.getBoundingClientRect().top - sectionTop);
      }

      document.documentElement.style.scrollBehavior = scrollBehavior;
    });
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});
